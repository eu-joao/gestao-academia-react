CREATE TABLE programa_treino (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nivel_experiencia varchar(255) NOT NULL,
    frequencia_semanal integer NOT NULL,
    tipo_estrutural varchar(255) NOT NULL,
    descricao varchar(255) NOT NULL,
    CONSTRAINT uk_programa_perfil UNIQUE (nivel_experiencia, frequencia_semanal)
);

CREATE TABLE aluno (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(255) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    google_subject varchar(255) UNIQUE,
    peso numeric(6, 2) NOT NULL,
    altura numeric(5, 2) NOT NULL,
    nivel_experiencia varchar(255) NOT NULL,
    frequencia_semanal integer NOT NULL,
    status varchar(255) NOT NULL,
    programa_atual_id bigint,
    CONSTRAINT fk_aluno_programa_atual FOREIGN KEY (programa_atual_id)
        REFERENCES programa_treino(id),
    CONSTRAINT ck_aluno_status CHECK (status IN ('ATIVO', 'INATIVO'))
);

CREATE INDEX idx_aluno_programa_atual ON aluno (programa_atual_id);

CREATE TABLE contrato (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id bigint NOT NULL,
    plano varchar(20) NOT NULL,
    data_inicio date NOT NULL,
    data_termino date NOT NULL,
    status varchar(255) NOT NULL,
    CONSTRAINT fk_contrato_aluno FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT ck_contrato_plano CHECK (plano IN ('MENSAL', 'TRIMESTRAL', 'SEMESTRAL')),
    CONSTRAINT ck_contrato_status CHECK (status IN ('ATIVO', 'ENCERRADO', 'CANCELADO'))
);

CREATE INDEX idx_contrato_aluno_status ON contrato (aluno_id, status, data_termino);
CREATE UNIQUE INDEX uk_contrato_ativo_aluno ON contrato (aluno_id) WHERE status = 'ATIVO';

CREATE TABLE cobranca (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id bigint NOT NULL,
    numero_parcela integer NOT NULL,
    data_vencimento date NOT NULL,
    valor numeric(10, 2) NOT NULL,
    data_pagamento date,
    status varchar(255) NOT NULL,
    CONSTRAINT fk_cobranca_contrato FOREIGN KEY (contrato_id) REFERENCES contrato(id),
    CONSTRAINT uk_cobranca_parcela UNIQUE (contrato_id, numero_parcela),
    CONSTRAINT ck_cobranca_status CHECK (status IN ('PENDENTE', 'PAGO', 'ATRASADO', 'CANCELADO'))
);

CREATE INDEX idx_cobranca_vencimento_status ON cobranca (data_vencimento, status);
CREATE INDEX idx_cobranca_contrato ON cobranca (contrato_id);

CREATE TABLE dia_treino (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programa_treino_id bigint NOT NULL,
    nome varchar(255) NOT NULL,
    ordem integer NOT NULL,
    CONSTRAINT fk_dia_programa FOREIGN KEY (programa_treino_id) REFERENCES programa_treino(id),
    CONSTRAINT uk_dia_ordem UNIQUE (programa_treino_id, ordem)
);

CREATE TABLE item_treino (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_treino_id bigint NOT NULL,
    nome_exercicio varchar(255) NOT NULL,
    musculatura_alvo varchar(255) NOT NULL,
    series integer NOT NULL,
    repeticoes varchar(255) NOT NULL,
    ordem integer NOT NULL,
    CONSTRAINT fk_item_dia FOREIGN KEY (dia_treino_id) REFERENCES dia_treino(id),
    CONSTRAINT uk_item_ordem UNIQUE (dia_treino_id, ordem)
);

CREATE TABLE sessao_treino (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id bigint NOT NULL,
    programa_treino_id bigint NOT NULL,
    dia_treino_id bigint NOT NULL,
    data_hora_conclusao timestamp without time zone NOT NULL,
    CONSTRAINT fk_sessao_aluno FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT fk_sessao_programa FOREIGN KEY (programa_treino_id) REFERENCES programa_treino(id),
    CONSTRAINT fk_sessao_dia FOREIGN KEY (dia_treino_id) REFERENCES dia_treino(id)
);

CREATE INDEX idx_sessao_aluno_programa_data ON sessao_treino (aluno_id, programa_treino_id, data_hora_conclusao);
