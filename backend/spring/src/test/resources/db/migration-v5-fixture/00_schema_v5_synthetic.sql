CREATE TABLE unidade (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(255) NOT NULL
);

CREATE TABLE plano (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo varchar(30) NOT NULL
);

CREATE TABLE programa_treino (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nivel_experiencia varchar(30) NOT NULL,
    frequencia_semanal integer NOT NULL,
    tipo_estrutural varchar(40) NOT NULL,
    descricao varchar(255) NOT NULL
);

CREATE TABLE aluno (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(255) NOT NULL,
    email varchar(255),
    cpf varchar(20) NOT NULL,
    telefone varchar(30) NOT NULL,
    data_nascimento date NOT NULL,
    peso numeric(6, 2) NOT NULL,
    altura numeric(6, 3) NOT NULL,
    nivel_experiencia varchar(30) NOT NULL,
    frequencia_semanal integer NOT NULL,
    status varchar(30) NOT NULL,
    CONSTRAINT uk_aluno_email_v5 UNIQUE (email)
);

CREATE TABLE contrato (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id bigint NOT NULL,
    plano_id bigint NOT NULL,
    unidade_id bigint NOT NULL,
    data_inicio date NOT NULL,
    data_termino date NOT NULL,
    status varchar(30) NOT NULL,
    CONSTRAINT fk_contrato_aluno_v5 FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT fk_contrato_plano_v5 FOREIGN KEY (plano_id) REFERENCES plano(id),
    CONSTRAINT fk_contrato_unidade_v5 FOREIGN KEY (unidade_id) REFERENCES unidade(id)
);

CREATE TABLE cobranca (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id bigint NOT NULL,
    data_vencimento date NOT NULL,
    valor numeric(10, 2) NOT NULL,
    data_pagamento date,
    status varchar(30) NOT NULL,
    CONSTRAINT fk_cobranca_contrato_v5 FOREIGN KEY (contrato_id) REFERENCES contrato(id)
);

CREATE TABLE dia_treino (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programa_treino_id bigint NOT NULL,
    nome_dia varchar(255) NOT NULL,
    ordem integer NOT NULL,
    CONSTRAINT fk_dia_programa_v5 FOREIGN KEY (programa_treino_id)
        REFERENCES programa_treino(id)
);

CREATE TABLE exercicio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(255) NOT NULL,
    musculatura_alvo varchar(255) NOT NULL
);

CREATE TABLE dia_treino_exercicio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_treino_id bigint NOT NULL,
    exercicio_id bigint NOT NULL,
    series integer NOT NULL,
    repeticoes integer NOT NULL,
    ordem integer NOT NULL,
    CONSTRAINT fk_dte_dia_v5 FOREIGN KEY (dia_treino_id) REFERENCES dia_treino(id),
    CONSTRAINT fk_dte_exercicio_v5 FOREIGN KEY (exercicio_id) REFERENCES exercicio(id)
);

CREATE TABLE treino_ativo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id bigint NOT NULL,
    programa_treino_id bigint NOT NULL,
    data_inicio date NOT NULL,
    status varchar(30) NOT NULL,
    CONSTRAINT fk_treino_aluno_v5 FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT fk_treino_programa_v5 FOREIGN KEY (programa_treino_id)
        REFERENCES programa_treino(id)
);
